export function searchIso6391(q: string): Iso6391[] {
  const n = q.trim().toLowerCase();
  if (!n) return ISO_639_1;
  return ISO_639_1.filter(
    (l) => l.code === n || l.name.toLowerCase().includes(n) || l.native.toLowerCase().includes(n),
  );
}

/** Heuristic source language for hiding the in-bubble translate control. */
export function guessMessageLang(text: string): string {
  const s = text.trim();
  if (!s) return "und";
  if (/[\u0600-\u06FF]/.test(s)) return "fa";
  if (/[\u0400-\u04FF]/.test(s)) return "ru";
  if (/[\u4E00-\u9FFF]/.test(s)) return "zh";
  if (/[\u3040-\u30FF]/.test(s)) return "ja";
  if (/[\uAC00-\uD7AF]/.test(s)) return "ko";
  if (/[\u0590-\u05FF]/.test(s)) return "he";
  if (/[\u0E00-\u0E7F]/.test(s)) return "th";
  if (/[\u0900-\u097F]/.test(s)) return "hi";
  if (/[\u0980-\u09FF]/.test(s)) return "bn";
  if (/[\u0C00-\u0C7F]/.test(s)) return "te";
  if (/[\u0A80-\u0AFF]/.test(s)) return "gu";
  if (/[\u10A0-\u10FF]/.test(s)) return "ka";
  if (/[\u0530-\u058F]/.test(s)) return "hy";
  return "en";
}

export function shouldShowTranslateButton(text: string, skip: string[]): boolean {
  const lang = guessMessageLang(text);
  if (lang === "und") return false;
  return !skip.includes(lang);
}
